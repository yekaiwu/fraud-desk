#!/bin/bash
# Install or update the GLDB app on the always-on Mac (docs/deploy.md). Idempotent: safe to re-run after
# every `git pull`. Run it ON the always-on Mac, from the install directory (~/.local/gldb-fraud).
#
#   deploy/install.sh              build, (re)start both launchd agents, print how to enable Funnel
#   deploy/install.sh --funnel     the same, then run `tailscale funnel --bg 3000` (PUBLIC internet exposure)
#
# Never touches ports 8080/8081 (LLM gateway, llama-server). Binds only 127.0.0.1:8000 and :3000.
set -euo pipefail

FUNNEL=0
for arg in "$@"; do
  case "$arg" in
    --funnel) FUNNEL=1 ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

if [ "$(uname)" != "Darwin" ]; then
  echo "This installer sets up launchd agents and only runs on macOS (uname=$(uname))." >&2
  exit 1
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT/deploy/.env.production"
LOG_DIR="$HOME/Library/Logs/gldb"
AGENT_DIR="$HOME/Library/LaunchAgents"
UID_NUM="$(id -u)"
LABELS=(com.jay.gldb-backend com.jay.gldb-frontend)

say() { printf '\n==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# macOS privacy (TCC) stops background services from reading Desktop, Documents and Downloads.
case "$ROOT" in
  "$HOME/Desktop"/*|"$HOME/Documents"/*|"$HOME/Downloads"/*)
    die "$ROOT is under a protected folder; launchd services cannot read it. Install to ~/.local/gldb-fraud (docs/deploy.md)." ;;
esac

command -v uv >/dev/null   || die "uv not found (https://docs.astral.sh/uv/). Install it first."
command -v node >/dev/null || die "node not found. Install Node 20+ (e.g. brew install node)."
command -v npm >/dev/null  || die "npm not found."
command -v openssl >/dev/null || die "openssl not found."
command -v lsof >/dev/null || die "lsof not found."

# ---------------------------------------------------------------- secrets (only if the file is missing)
NEW_PASSWORD=""
if [ -f "$ENV_FILE" ]; then
  say "Keeping existing $ENV_FILE"
  # Older files (shared-password sign-in) have no username; add the default and keep the existing password.
  if ! grep -q '^GLDB_SITE_USERNAME=' "$ENV_FILE"; then
    printf '\nGLDB_SITE_USERNAME=officer\n' >> "$ENV_FILE"
    say "Added GLDB_SITE_USERNAME=officer to $ENV_FILE (sign in as officer with the existing password)."
  fi
else
  say "Generating $ENV_FILE"
  NEW_PASSWORD="$(openssl rand -base64 24 | tr -d '/+=\n' | cut -c1-24)"
  umask 077
  {
    echo "# Generated by deploy/install.sh on $(date '+%Y-%m-%d %H:%M:%S'). See deploy/env.production.example for every variable."
    echo "GLDB_SITE_USERNAME=officer"
    echo "GLDB_SITE_PASSWORD=$NEW_PASSWORD"
    echo "GLDB_SESSION_SECRET=$(openssl rand -hex 32)"
    echo "GLDB_PROXY_SECRET=$(openssl rand -hex 32)"
    echo "GLDB_BACKEND_URL=http://127.0.0.1:8000"
    echo "GLDB_RATE_CASES_PER_HOUR=10"
    echo "GLDB_RATE_REVIEWS_PER_MIN=30"
    echo "GLDB_MAX_ACTIVE_JOBS=6"
    echo "GLDB_DATA_DIR=$ROOT/data"
    echo "GLDB_REGISTRY_PATH=$ROOT/samples/registry.json"
    echo "GLDB_CORS_ORIGINS=http://127.0.0.1:3000"
    echo "# LLM: see deploy/env.production.example (local-LLM profile). Without a key the Fake client is used."
  } > "$ENV_FILE"
  chmod 600 "$ENV_FILE"
fi
chmod 600 "$ENV_FILE"

# Validate what the services will actually read (fail now, not at 3 a.m.).
set -a; . "$ENV_FILE"; set +a
[ "${#GLDB_SITE_USERNAME}" -ge 3 ]  || die "GLDB_SITE_USERNAME in $ENV_FILE must be at least 3 characters."
[ "${#GLDB_SITE_PASSWORD}" -ge 12 ] || die "GLDB_SITE_PASSWORD in $ENV_FILE must be at least 12 characters."
[ "${#GLDB_SESSION_SECRET}" -ge 32 ] || die "GLDB_SESSION_SECRET in $ENV_FILE must be at least 32 characters."
[ "${#GLDB_PROXY_SECRET}" -ge 16 ]   || die "GLDB_PROXY_SECRET in $ENV_FILE must be at least 16 characters."
case "${GLDB_BACKEND_URL:-}" in http://127.0.0.1:8000|http://localhost:8000) ;; *) die "GLDB_BACKEND_URL must point at the loopback backend (http://127.0.0.1:8000)." ;; esac

# ---------------------------------------------------------------- stop our own agents so the ports and build dir are free
say "Stopping any running GLDB agents (re-run safe)"
for label in "${LABELS[@]}"; do
  launchctl bootout "gui/$UID_NUM/$label" 2>/dev/null || true
done
sleep 1

say "Checking ports 8000 and 3000 are free"
for port in 8000 3000; do
  if lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1; then
    lsof -nP -iTCP:"$port" -sTCP:LISTEN >&2 || true
    die "port $port is in use by something that is not a GLDB agent. Free it or change the port (never use 8080/8081: LLM gateway)."
  fi
done

# ---------------------------------------------------------------- build
say "Backend dependencies (uv sync --extra ocr: the local OCR readers)"
( cd "$ROOT" && uv sync --extra ocr )

say "Frontend dependencies and production build"
(
  cd "$ROOT/frontend"
  npm ci
  # The browser must talk to the same-origin /api proxy: make sure nothing from the shell overrides that.
  env -u NEXT_PUBLIC_API_BASE_URL -u NEXT_PUBLIC_USE_MOCK npm run build
)

# ---------------------------------------------------------------- launchd agents
say "Installing launchd agents"
mkdir -p "$LOG_DIR" "$AGENT_DIR" "$GLDB_DATA_DIR"
AGENT_PATH="$(dirname "$(command -v uv)"):$(dirname "$(command -v node)"):/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin"
for label in "${LABELS[@]}"; do
  name="${label#com.jay.}"   # gldb-backend / gldb-frontend
  sed -e "s#__ROOT__#$ROOT#g" -e "s#__HOME__#$HOME#g" -e "s#__PATH__#$AGENT_PATH#g" \
    "$ROOT/deploy/launchd/$label.plist.template" > "$AGENT_DIR/$label.plist"
  chmod 644 "$AGENT_DIR/$label.plist"
  plutil -lint "$AGENT_DIR/$label.plist" >/dev/null
  launchctl bootstrap "gui/$UID_NUM" "$AGENT_DIR/$label.plist"
  launchctl enable "gui/$UID_NUM/$label" 2>/dev/null || true
  echo "  loaded $label (logs: $LOG_DIR/${name#gldb-}.log)"
done

say "Waiting for the services"
ok=0
for _ in $(seq 1 40); do
  if curl -fsS --max-time 2 http://127.0.0.1:8000/health >/dev/null 2>&1 \
     && [ "$(curl -s -o /dev/null --max-time 2 -w '%{http_code}' http://127.0.0.1:3000/login)" = "200" ]; then ok=1; break; fi
  sleep 1
done
[ "$ok" = 1 ] || die "services did not come up. Read $LOG_DIR/backend.log and $LOG_DIR/frontend.log"
echo "  backend  http://127.0.0.1:8000/health  ok"
echo "  frontend http://127.0.0.1:3000/login   ok"
[ "$(curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1:8000/cases)" = "401" ] || die "backend answered without the proxy secret: GLDB_PROXY_SECRET is not active."

# ---------------------------------------------------------------- tailscale
TS=""
if command -v tailscale >/dev/null 2>&1; then TS="$(command -v tailscale)"
elif [ -x /Applications/Tailscale.app/Contents/MacOS/Tailscale ]; then TS=/Applications/Tailscale.app/Contents/MacOS/Tailscale; fi

if [ "$FUNNEL" = 1 ]; then
  [ -n "$TS" ] || die "tailscale CLI not found (looked on PATH and in /Applications/Tailscale.app)."
  say "Enabling Tailscale Funnel on port 3000: this makes the app reachable from the PUBLIC internet"
  "$TS" funnel --bg 3000
else
  say "Funnel NOT enabled (run again with --funnel when you are ready)"
  cat <<MSG
  Prerequisites (Tailscale admin console, docs/deploy.md section 1): MagicDNS and HTTPS certificates enabled,
  the Funnel node attribute granted to this Mac in the tailnet policy, and this Mac signed in to Tailscale.
  Then:   ${TS:-tailscale} funnel --bg 3000        (or: deploy/install.sh --funnel)
  Off:    deploy/uninstall.sh --funnel-off
MSG
fi

if [ -n "$TS" ]; then
  DNS="$("$TS" status --json 2>/dev/null | ( cd "$ROOT" && uv run --no-sync python -c 'import json,sys; print(json.load(sys.stdin)["Self"]["DNSName"].rstrip("."))' ) 2>/dev/null || true)"
  if [ -n "$DNS" ]; then
    if [ "$FUNNEL" = 1 ]; then say "Public URL: https://$DNS/"; else say "Once Funnel is on, the URL will be: https://$DNS/"; fi
  fi
fi

if [ -n "$NEW_PASSWORD" ]; then
  cat <<MSG

################################################################################
  Sign-in (password shown ONCE; both stored in $ENV_FILE):

      username: officer
      password: $NEW_PASSWORD

################################################################################
MSG
fi
say "Done. Status: deploy/status.sh"
