"""The tamper catalogue (docs/test-data-and-eval.md section 4.3, plan 9.2).

``TAMPERS`` maps an id to a ``TamperDef``: channel, scenarios, renders, the rule(s) expected (any-of),
acceptable extras (``may_also_fire``), and the flags ``hard`` / ``known_miss`` / ``weak`` that keep a
row out of the headline core recall. Rule ids are checked against ``checks.registry.all_checks()`` by
``unregistered_rules``; a tamper whose expected rule is not registered is reported as
"rule not implemented: gap", never an error.
"""

from __future__ import annotations

from scripts._gen.schema import Channel, G, Render, Scenario

DIGITAL: list[Render] = ["digital"]
DEGRADE: list[Render] = ["digital", "scan_hq", "scan_lq", "photo"]
SCAN_ONLY: list[Render] = ["scan_hq", "scan_lq", "photo"]


class TamperDef(G):
    id: str
    edit: str
    channel: Channel
    scenarios: list[Scenario]
    renders: list[Render]
    expected_any_of: list[str]
    may_also_fire: list[str] = []
    hard: bool = False
    known_miss: bool = False
    weak: bool = False
    target_desc: str = ""


def _t(
    id: str,
    edit: str,
    channel: Channel,
    scn: str,
    renders: list[Render],
    exp: list[str],
    may: list[str] | None = None,
    target: str = "",
    **flags: bool,
) -> TamperDef:
    names = {"L": "loan", "K": "kyc", "A": "aml"}
    return TamperDef(
        id=id,
        edit=edit,
        channel=channel,
        scenarios=[names[c] for c in scn.split()],  # type: ignore[misc]
        renders=renders,
        expected_any_of=exp,
        may_also_fire=may or [],
        target_desc=target,
        **flags,
    )


