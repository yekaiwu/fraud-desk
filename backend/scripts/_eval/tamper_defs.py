TAMPERS: dict[str, TamperDef] = {t.id: t for t in _ROWS}


def tamper_ids() -> list[str]:
    return list(TAMPERS)


def unregistered_rules(td: TamperDef, registered: set[str]) -> list[str]:
    """Expected rules of ``td`` that are not registered checks ("rule not implemented: gap")."""
    return [r for r in td.expected_any_of if r not in registered]


def registered_rules() -> set[str]:
    """Rule ids of every registered check (empty set when the registry cannot be imported)."""
    try:
        from app.checks.registry import all_checks

        out: set[str] = set()
        for c in all_checks():
            rid = getattr(c, "rule", None) or getattr(c, "id", None) or getattr(c, "name", None)
            if rid:
                out.add(str(rid))
        return out
    except Exception:  # pragma: no cover - registry import problems are reported by the caller
        return set()
