"""Generate ``docs/check-catalogue.md`` from the registered checks (docs/compliance.md 3.2).

Usage::

    uv run python backend/scripts/gen_check_catalogue.py [--out docs/check-catalogue.md] [--check]

``--check`` writes nothing and exits 1 if the file on disk differs from the fresh output (CI use),
else 0. The output is byte-stable: no timestamps, LF line endings, final newline, a fixed sort.
The same data is served by ``GET /rules`` so the page and the API cannot diverge.
"""

