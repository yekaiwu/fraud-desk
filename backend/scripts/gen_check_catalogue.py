# core/builtin_checks.py: info checks emitted from pipeline warnings (plan section)
BUILTIN_RULES: dict[str, str] = {"doc_unreadable": "8.5", "doc_unclassified": "5.3"}

# registered checks that the plan does not list, with the reason
ADDED_RULES: dict[str, str] = {
    "file_reuse": "0.4 duplicate detection (file hash), added at R0",
}

STAGE_SECTIONS: tuple[tuple[str, str], ...] = (
    ("forensics", "Forensics"),
    ("rules", "Rules (per document)"),
    ("crossdoc", "Cross-document"),
)
STAGE_RANK = {stage: i for i, (stage, _) in enumerate(STAGE_SECTIONS)}

TABLE_HEADER = (
    "| Rule | Default severity | Applies to | Requires | Use cases | What it checks "
    "| Tamper caught | Version |"
)
TABLE_RULE = "|---|---|---|---|---|---|---|---|"


def collect() -> list[CheckMeta]:
    """Discover and return every registered check, sorted by (stage order, rule)."""
    from app.checks.registry import all_checks, discover

    discover()
    return list(all_checks())


def ruleset_version(checks: Sequence[CheckMeta]) -> str:
    """Same value as ``Provenance.ruleset_version``: the core helper, so the two cannot drift."""
    from app.core.provenance import ruleset_version as core_ruleset_version

    return core_ruleset_version(checks)


def _cell(text: str | None) -> str:
    """One table cell: newlines collapsed to a space, ``|`` escaped."""
    if text is None or not str(text).strip():
        return "-"
    return " ".join(str(text).split()).replace("|", "\\|")


def _join(values: frozenset[str] | set[str], *, empty: str = "-") -> str:
    if not values:
        return empty
    if set(values) == {"*"}:
        return "any file"
    return ", ".join(sorted(values))


def _sorted(checks: Sequence[CheckMeta]) -> list[CheckMeta]:
    return sorted(checks, key=lambda c: (STAGE_RANK.get(c.stage, len(STAGE_RANK)), c.rule))


def _row(c: CheckMeta) -> str:
    cells = [
        f"`{c.rule}`",
        c.severity,
        _join(c.applies_to),
        _join(c.requires),
        _join(c.use_cases),
        _cell(c.description),
        _cell(c.tamper),
        _cell(c.version),
    ]
    return "| " + " | ".join(cells) + " |"


def _reason(c: CheckMeta, builtin_rules: Mapping[str, str]) -> str:
    if c.rule in builtin_rules:
        return f"built-in info check, emitted from pipeline warnings (plan {builtin_rules[c.rule]})"
    if c.rule in ADDED_RULES:
        return ADDED_RULES[c.rule]
    return "unplanned"


def render_catalogue(
    checks: Sequence[CheckMeta],
    *,
    plan_rules: Mapping[str, str] = PLAN_RULES,
    builtin_rules: Mapping[str, str] = BUILTIN_RULES,
) -> str:
    """The full Markdown page. Pure and deterministic."""
    ordered = _sorted(checks)
    registered = {c.rule for c in ordered}
    missing = sorted(
        (r for r in plan_rules if r not in registered),
        key=lambda r: (plan_rules[r], r),
    )
    extra = [c for c in ordered if c.rule not in plan_rules]

    out: list[str] = [GENERATED_MARKER, "# Check catalogue", CAVEAT, ""]
    out.append(
        f"Ruleset version: `{ruleset_version(ordered)}` | Checks registered: {len(ordered)} "
        f"| Planned in the plan but not registered: {len(missing)}"
    )
    out += [
        "",
        "## How to read this",
        "",
        "- Default severity is a starting guess; it is recalibrated from the eval "
        "(docs/validation-report.md).",
        "- Coverage is the number of checks that ran divided by the number that applied to the "
        "case; a check that could not run is listed as skipped, never as passed.",
        '- "Tamper caught" is the edit the check is meant to catch.',
        "- This file shows the code defaults only. Officers can switch a check off, change its "
        "severity or edit its name, description and note in the check catalogue (`GET /rules` "
        "shows the effective settings, `GET /rules/changes` the change log); those overrides are "
        "never written to this file.",
    ]
    for stage, heading in STAGE_SECTIONS:
        out += ["", f"## {heading}", "", TABLE_HEADER, TABLE_RULE]
        out += [_row(c) for c in ordered if c.stage == stage]
    out += [
        "",
        "## Planned but not registered (gap, plan 0.6)",
        "",
    ]
    if missing:
        out += ["| Rule | Plan section |", "|---|---|"]
        out += [f"| `{r}` | {plan_rules[r]} |" for r in missing]
    else:
        out.append("None")
    out += ["", "## Registered but not in the plan", ""]
    if extra:
        out += ["| Rule | Stage | Reason |", "|---|---|---|"]
        out += [f"| `{c.rule}` | {c.stage} | {_cell(_reason(c, builtin_rules))} |" for c in extra]
    else:
        out.append("None")
    return "\n".join(out) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/check-catalogue.md")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output file")
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if the file on disk differs from the fresh output",
    )
    args = parser.parse_args(argv)

    try:
        checks = collect()
    except Exception as exc:  # discover() names the failing module in the message
        print(f"gen_check_catalogue: cannot collect checks: {exc}", file=sys.stderr)
        return 1
    fresh = render_catalogue(checks)
    out: Path = args.out

    if args.check:
        current = out.read_bytes().decode("utf-8") if out.exists() else None
        if current == fresh:
            print(f"{out}: up to date ({len(checks)} checks)")
            return 0
        print(
            f"{out}: stale or missing; regenerate with: "
            "uv run python backend/scripts/gen_check_catalogue.py",
            file=sys.stderr,
        )
        return 1

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(fresh.encode("utf-8"))
    print(f"wrote {out} ({len(checks)} checks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
