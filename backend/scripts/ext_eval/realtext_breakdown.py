"""RealText-V2 forensic results split by what the forgery looks like.

Reads the per-image rows written by ``forensic_runner.py`` (``forensics-realtext-images.csv``) and,
for the forged images, the annotation report (anomaly types, written by an LLM and not checked, so a
type can be wrong) and the mask (share of the page that was edited). Reports the detection rate of the
repo's pixel checks per type and per edit size, next to the false-alarm rate on pristine images, to
show WHERE classical forensics has any signal and where it has none.

    uv run python -I backend/scripts/ext_eval/realtext_breakdown.py \
        --root $EXTERNAL_DATA/realtext-v2 \
        --images docs/eval-results/external/forensics-realtext-images.csv \
        --out docs/eval-results/external/forensics-realtext-breakdown.md

Files under ``--root`` are untrusted data: read as text and decoded with Pillow only.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

_BACKEND = Path(__file__).resolve().parents[2]
if str(_BACKEND) not in sys.path:
    sys.path.insert(0, str(_BACKEND))

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

from scripts._eval import metrics as mx  # noqa: E402

MODE = "resize1600_jpeg85"
TYPE_NAMES = ("visual_clumsy", "logical_fraud", "semantic_subtle")
_ANOMALY = re.compile(r"###\s*ANOMALY_\d+:\s*([^\n(]*)")
SAFE_ID = re.compile(r"^[A-Za-z0-9_\-]{1,80}$")


def anomaly_types(report: str) -> set[str]:
    out = set()
    for raw in _ANOMALY.findall(report):
        key = re.sub(r"[^a-z]+", "_", raw.strip().lower()).strip("_")
        for name in TYPE_NAMES:
            if key.startswith(name):
                out.add(name)
    return out


def mask_share(path: Path) -> float | None:
    try:
        with Image.open(path) as im:
            arr = np.asarray(im.convert("L"))
    except OSError:
        return None
    return float((arr > 127).mean())


def rate(k: int, n: int) -> str:
    if not n:
        return "n/a"
    lo, hi = mx.wilson(k, n)
    return f"{k}/{n} = {k / n:.2f} [{lo:.2f}-{hi:.2f}]"


def load_rows(images_csv: Path, mode: str) -> list[dict[str, str]]:
    with images_csv.open(newline="", encoding="utf-8") as fh:
        return [r for r in csv.DictReader(fh) if r["mode"] == mode and r["ok"] == "True"]


def classify(
    rows: Sequence[dict[str, str]], root: Path
) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    forged, genuine = [], []
    for r in rows:
        sid = r["sample_id"]
        if r["label"] != "forged":
            genuine.append(r)
            continue
        if not SAFE_ID.match(sid):
            continue
        report = root / "train" / "report" / f"{sid}_report.md"
        types = (
            anomaly_types(report.read_text(encoding="utf-8", errors="replace"))
            if report.exists()
            else set()
        )
        share = mask_share(root / "train" / "mask" / f"{sid}_mask.png")
        forged.append(
            {
                "types": types,
                "share": share,
                "any": r["pixel_any"] == "True",
                "severe": r["worst_severity"] in {"2", "3"},
                "row": r,
            }
        )
    return forged, genuine


def type_sentence(forged: list[dict[str, Any]]) -> str:
    n = len(forged)
    counts = {name: sum(name in i["types"] for i in forged) for name in TYPE_NAMES}
    named = ", ".join(f"`{k}` {v}" for k, v in counts.items())
    return (
        f"The reports name these anomaly types on the {n} forged images: {named}. Nearly every forged image is "
        "labelled with all of them, so the labels do not separate the images and no per-type rate is given."
    )


def build_markdown(forged: list[dict[str, Any]], genuine: list[dict[str, str]]) -> str:
    g_any = sum(r["pixel_any"] == "True" for r in genuine)
    g_sev = sum(r["worst_severity"] in {"2", "3"} for r in genuine)
    lines = [
        "# RealText-V2: detection by size of the edit\n",
        f"Generated by `backend/scripts/ext_eval/realtext_breakdown.py` from the `{MODE}` rows of the forensic runner "
        "(the same images, the same checks; nothing re-run, nothing tuned). The anomaly types come from the dataset's "
        "LLM-written reports and were not verified; the size is the share of the page covered by the mask.\n",
        f"Reference: false alarms on the {len(genuine)} pristine images: any pixel flag {rate(g_any, len(genuine))}; "
        f"medium or high {rate(g_sev, len(genuine))}. A size band is only 'detected' in a useful sense when its "
        "rate clearly exceeds that reference.\n",
        "## By anomaly type named in the report\n",
        type_sentence(forged),
        "",
    ]

    def row(label: str, items: list[dict[str, Any]]) -> str:
        return f"| {label} | {len(items)} | {rate(sum(i['any'] for i in items), len(items))} | {rate(sum(i['severe'] for i in items), len(items))} |"

    lines += [
        "",
        "## By size of the edit (share of the page in the mask)\n",
        "| Edited share of page | Forged images | Any pixel flag | Medium or high |",
        "|---|---|---|---|",
    ]
    bins = [(0.0, 0.005, "below 0.5%"), (0.005, 0.02, "0.5% to 2%"), (0.02, 1.01, "2% or more")]
    for lo, hi, label in bins:
        lines.append(
            row(label, [i for i in forged if i["share"] is not None and lo <= i["share"] < hi])
        )
    lines += [
        "",
        "## How to read this\n",
        "- These are the same detectors and the same images as the main RealText-V2 report; this only cuts them differently. "
        "Samples per cell are small (tens of images), so read the intervals.",
        "- Why classical forensics is weak here: ELA looks for a patch that was saved at a different JPEG quality than the "
        "rest, copy-move for two identical areas, noise analysis for a patch with different sensor noise. A generative "
        "model that redraws a word or a region writes the whole output in one pass and the file is saved once, so the edited "
        "text has the same compression, noise and texture as its surroundings. A few percent of a 2500 x 3500 page also "
        "disappears in page-level statistics.",
        "- A flag that fires on pristine images about as often as on forged ones carries no signal. Where a band's rate does not "
        "clearly exceed the reference, treat the detector as blind to that case, not as lucky.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", required=True, type=Path)
    ap.add_argument("--images", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--mode", default=MODE)
    args = ap.parse_args(argv)
    forged, genuine = classify(load_rows(args.images, args.mode), args.root)
    text = build_markdown(forged, genuine)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
